package odigosenterpriseauthextension

import (
	"context"
	"errors"
	"fmt"
	"os"
	"strings"
	"time"

	"go.opentelemetry.io/collector/component"
	"go.opentelemetry.io/collector/component/componentstatus"
	"go.uber.org/zap"

	"github.com/odigos-io/odigos/odigosauth"
)

// OnPremTokenEnvVar is populated by helm from the odigos-pro secret, as for the other components.
const OnPremTokenEnvVar = "ODIGOS_ONPREM_TOKEN"

// ErrTokenExpired is reported to the host when a token that was valid at startup later expires.
var ErrTokenExpired = errors.New("odigos enterprise on-prem token expired")

// authExtension gates the enterprise collector on a valid Odigos on-prem token. The other
// components call odigosauth.AssertEnterpriseOdigosToken from their own main(); the collector's
// main is generated by the OpenTelemetry Collector Builder and overwritten on every regeneration,
// so an extension is the supported place to run code over the collector's lifecycle.
type authExtension struct {
	logger *zap.Logger

	cancel context.CancelFunc
	// watcherDone closes when the expiration goroutine returns, so Shutdown can wait for it
	// instead of racing it.
	watcherDone chan struct{}

	// expirationChannel is swappable in tests so expiry can be exercised without minting a JWT
	// that expires seconds from now.
	expirationChannel func() (<-chan time.Time, error)
	// verifyToken is swappable in tests for the same reason.
	verifyToken func(string) (string, error)
}

var _ extensionWithLifecycle = (*authExtension)(nil)

// extensionWithLifecycle is component.Component, spelled out so the compile-time assertion above
// fails loudly if the collector API changes shape.
type extensionWithLifecycle interface {
	Start(context.Context, component.Host) error
	Shutdown(context.Context) error
}

func newAuthExtension(logger *zap.Logger) *authExtension {
	return &authExtension{
		logger:            logger,
		expirationChannel: odigosauth.TokenExpirationChannel,
		verifyToken:       odigosauth.VerifyOnpremToken,
	}
}

// Start refuses to start the collector if the token is missing or invalid, the extension-level
// equivalent of the os.Exit(1) the other components perform.
func (a *authExtension) Start(_ context.Context, host component.Host) error {
	token := strings.TrimSpace(os.Getenv(OnPremTokenEnvVar))
	if token == "" {
		return fmt.Errorf("%s is not set: the enterprise collector requires an Odigos on-prem token", OnPremTokenEnvVar)
	}

	audience, err := a.verifyToken(token)
	if err != nil {
		return fmt.Errorf("failed to verify Odigos on-prem token: %w", err)
	}
	a.logger.Info("Odigos on-prem token verified", zap.String("audience", audience))

	// A token valid now can expire later. Report a fatal error rather than os.Exit, so the
	// collector shuts down through its normal path.
	expiration, err := a.expirationChannel()
	if err != nil {
		return fmt.Errorf("failed to determine Odigos on-prem token expiration: %w", err)
	}

	// Detached from Start's ctx on purpose: that one is cancelled once startup returns, but the
	// watcher has to outlive it and run until Shutdown cancels it.
	var ctx context.Context
	ctx, a.cancel = context.WithCancel(context.Background())
	a.watcherDone = make(chan struct{})
	go a.watchExpiration(ctx, host, expiration)

	return nil
}

func (a *authExtension) watchExpiration(ctx context.Context, host component.Host, expiration <-chan time.Time) {
	defer close(a.watcherDone)

	select {
	case <-ctx.Done():
		return
	case <-expiration:
		// Both cases can be ready at once if the token expires as the collector shuts down, and
		// select then picks at random. Shutdown wins.
		if ctx.Err() != nil {
			return
		}
		a.logger.Error("Odigos on-prem token expired, shutting down the collector; contact Odigos support to issue a new one")
		componentstatus.ReportStatus(host, componentstatus.NewFatalErrorEvent(ErrTokenExpired))
	}
}

func (a *authExtension) Shutdown(_ context.Context) error {
	if a.cancel == nil {
		return nil
	}
	a.cancel()
	<-a.watcherDone
	return nil
}
